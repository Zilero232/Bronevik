"""components.json -> the two generated Inno Setup includes.

components.iss  [Types] (presets), [Components] (category\\id tree), [CustomMessages] (ru/en texts) and
                OtmCatalogInit, the table the wizard code reads (installer/src/components/catalog.iss).
files.iss       [Files]: every package into {code:OtmModsDir}, every preview as a dontcopy temp file.

Inno component names are `<category>\\<id>`; ComponentsList rows follow the [Components] order, which the
catalog table repeats. Paths in files.iss use the OtmPackagesDir / OtmBuildDir defines of setup.iss.
"""
from ..manifest.model import LANGUAGES

# A ';' comment is only valid inside a non-code section, so it always follows a section tag.
HEADER = '; Generated by tools/build/setupkit from installer/catalog/catalog.json and the package layout. Do not edit.\n'


def component_name(component):
    return '%s\\%s' % (component.category, component.id)


def _quote(value):
    return '"%s"' % value.replace('"', '""')


def _pascal(value):
    return "'%s'" % (value or '').replace("'", "''")


def _message(value):
    return value.replace('\r\n', '\n').replace('\n', '%n')


def _types(manifest, component):
    """Inno types of a component; required ones sit in every type so `fixed` never unticks them."""
    if component.required:
        return [preset.id for preset in manifest.presets]
    custom = [preset.id for preset in manifest.presets if preset.custom]
    return list(component.presets) + (custom if component.default else [])


def _messages(manifest):
    lines = ['[CustomMessages]']
    for language in LANGUAGES:
        for preset in manifest.presets:
            lines.append('%s.OtmType_%s=%s' % (language, preset.id, _message(getattr(preset.title, language))))
            lines.append('%s.OtmTypeDesc_%s=%s' % (language, preset.id, _message(getattr(preset.description, language))))
        for category in manifest.categories:
            lines.append('%s.OtmCat_%s=%s' % (language, category.id, _message(getattr(category.title, language))))
            lines.append('%s.OtmCatDesc_%s=%s' % (language, category.id, _message(getattr(category.description, language))))
        for component in manifest.components:
            lines.append('%s.OtmComp_%s=%s' % (language, component.id, _message(getattr(component.title, language))))
            lines.append('%s.OtmCompDesc_%s=%s' % (language, component.id, _message(getattr(component.description, language))))
            lines.append('%s.OtmCompFair_%s=%s' % (language, component.id, _message(getattr(component.fair_play, language))))
    return lines


def _catalog_code(manifest):
    names = dict((component.id, component_name(component)) for component in manifest.components)
    lines = ['[Code]', 'procedure OtmCatalogInit;', 'begin', '  SetArrayLength(OtmCatalog, 0);']
    for category in manifest.categories:
        lines.append("  OtmCatalogAdd(%s, %s, True, False, '', '', '', '');" % (_pascal(category.id), _pascal(category.id)))
        for component in manifest.components:
            if component.category != category.id:
                continue
            depends = ','.join(names[dependency] for dependency in component.dependencies)
            preview = component.preview.image.split('/')[-1] if component.preview.image else ''
            lines.append('  OtmCatalogAdd(%s, %s, False, %s, %s, %s, %s, %s);' % (
                _pascal(names[component.id]), _pascal(component.id), 'True' if component.required else 'False',
                _pascal(component.file), _pascal(preview), _pascal(component.preview.video), _pascal(depends)))
    lines.extend(['end;', ''])
    return lines


def components_iss(manifest):
    presets = manifest.presets
    lines = ['#define OtmModpackVersion %s' % _quote(manifest.modpack_version),
             '#define OtmOwnedPatterns %s' % _quote(';'.join(manifest.owned_patterns)),
             '', '[Types]', HEADER.rstrip('\n')]
    for preset in presets:
        flags = '; Flags: iscustom' if preset.custom else ''
        lines.append('Name: %s; Description: "{cm:OtmType_%s}"%s' % (_quote(preset.id), preset.id, flags))
    lines.extend(['', '[Components]'])
    for category in manifest.categories:
        members = [component for component in manifest.components if component.category == category.id]
        category_types = [preset.id for preset in presets if any(preset.id in _types(manifest, member) for member in members)]
        types = '; Types: %s' % ' '.join(category_types) if category_types else ''
        lines.append('Name: %s; Description: "{cm:OtmCat_%s}"%s' % (_quote(category.id), category.id, types))
        for component in members:
            component_types = _types(manifest, component)
            types = '; Types: %s' % ' '.join(component_types) if component_types else ''
            flags = '; Flags: fixed' if component.required else ''
            lines.append('Name: %s; Description: "{cm:OtmComp_%s}"%s%s' % (_quote(component_name(component)), component.id, types, flags))
    lines.append('')
    lines.extend(_messages(manifest))
    lines.append('')
    lines.extend(_catalog_code(manifest))
    return '\n'.join(lines)


def files_iss(manifest):
    lines = ['[Files]', HEADER.rstrip('\n')]
    for component in manifest.components:
        lines.append('Source: "{#OtmPackagesDir}\\%s"; DestDir: "{code:OtmModsDir}"; Components: %s; Flags: ignoreversion' % (
            component.file, component_name(component)))
    previews = sorted(set(component.preview.image for component in manifest.components if component.preview.image))
    for preview in previews:
        lines.append('Source: "{#OtmBuildDir}\\%s"; Flags: dontcopy' % preview.replace('/', '\\'))
    return '\n'.join(lines) + '\n'
